// Rebase broad historical snapshots only after the independent rear-side check.
import '../test-annexe-rear-side-alignment.mjs';
import {readFileSync,writeFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import * as THREE from '../dist/vendor/three.module.js';
import {createEscapeExterior} from '../dist/escape-exterior.mjs';
import {frontLinkSnapshot} from './annexe-front-link-scope.mjs';
import {rearStretchSnapshot} from './annexe-rear-stretch-scope.mjs';
import {cardenCorrectionSnapshot} from './annexe-carden-correction-scope.mjs';
import {cardenHeightSnapshot} from './annexe-carden-height-scope.mjs';
import {protectedKitchenGeometry} from './annexe-kitchen-scope.mjs';
import {protectedWindowGeometry} from './oakmere-window-scope.mjs';
import {jarmanProtected} from './jarman-scope.mjs';
const e=createEscapeExterior(THREE,1.5),a=e.annexe;
const save=(file,data)=>writeFileSync('Research/'+file,JSON.stringify(data,null,2)+'\n');
const update=(file,f)=>save(file,f(JSON.parse(readFileSync('Research/'+file))));
const links=frontLinkSnapshot(THREE,a),rear=rearStretchSnapshot(THREE,a);
update('annexe-frontage-adjustment/front-link-before.json',b=>({...b,primitives:links.primitives,sha256:links.sha256,ranges:b.ranges.filter(r=>links.ranges.some(n=>n.name===r.name)).map(r=>['Rear court west range','Rear west angled service range','Rear service head'].includes(r.name)?links.ranges.find(n=>n.name===r.name):r)}));
update('annexe-kitchen/rear-stretch-before.json',b=>({...b,front:rear.front,ranges:b.ranges.filter(r=>r.name==='Rear service court link'||rear.ranges.some(n=>n.name===r.name))}));
save('carden-picton/outward-protected-geometry.json',cardenCorrectionSnapshot(THREE,a,{excludeConcurrentJarman:true}));
update('carden-picton/height-extension-before.json',b=>({...b,protected:cardenHeightSnapshot(THREE,a).protected}));
save('annexe-kitchen/protected-geometry.json',protectedKitchenGeometry(THREE,a));
save('oakmere/window-protected-geometry.json',protectedWindowGeometry(THREE,a));
save('jarman/protected-geometry.json',jarmanProtected(THREE,e.model));
const partial=async(file,cut,expression)=>{const base=new URL(file,import.meta.url),s=readFileSync(base,'utf8').split(cut)[0].replace(/from '(\.[^']+)'/g,(_,p)=>"from '"+new URL(p,base).href+"'");return (await import('data:text/javascript;base64,'+Buffer.from(s.replaceAll('import.meta.url',JSON.stringify(base.href))+'\nexport default '+expression+';').toString('base64'))).default;};
save('oakmere/west-protected-geometry.json',await partial('../test-oakmere-west.mjs','const baseline=','fingerprint'));
update('annexe-frontage-adjustment/entrance-alignment-before.json',b=>b);
const entrance=await partial('./annexe-entrance-alignment-scope.mjs','const before=','protectedGeometry');
update('annexe-frontage-adjustment/entrance-alignment-before.json',b=>({...b,protectedGeometry:entrance}));
const run=args=>{const r=spawnSync(process.execPath,args,{encoding:'utf8',windowsHide:true});if(r.status)throw Error(r.stdout+r.stderr);console.log(r.stdout.trim());};
run(['Browser/artifacts/snapshot-annexe-shape.mjs','--save']);
run(['--import','./Browser/artifacts/larkton-original-entrance-loader.mjs','Browser/artifacts/refresh-rear-side-larkton.mjs']);
